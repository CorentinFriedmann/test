// Embeds game/data/*.csv in src/data/generated.js (text import usable by Node tests and by the esbuild bundle).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const names = ['maree', 'maree_effets', 'stations', 'menace', 'monde'];
const raw = {};
for (const n of names) raw[n] = readFileSync(resolve(root, 'data', `${n}.csv`), 'utf8');
const out = `// GENERATED by scripts/gen-data.mjs from data/*.csv. Do not edit.\nexport const RAW_CSV = ${JSON.stringify(raw, null, 1)};\n`;
writeFileSync(resolve(root, 'src/data/generated.js'), out);
console.log(`generated src/data/generated.js (${names.length} CSV files)`);
